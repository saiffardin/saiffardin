// Writes README.md. Every visual is a <picture> so GitHub swaps light/dark with the viewer's theme.
import { writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import { profile } from '../data/profile.mjs';
import { ROOT } from './lib.mjs';

const pic = (name, alt, attrs = 'width="100%"') => `<picture>
  <source media="(prefers-color-scheme: dark)" srcset="./assets/${name}-dark.svg">
  <img src="./assets/${name}-light.svg" alt="${alt.replace(/"/g, '&quot;')}" ${attrs}>
</picture>`;

export async function writeReadme() {
  const p = profile;

  const links = p.links.map((l) => `<a href="${l.url}">${pic(`link-${l.slug}`, l.label, 'height="34"')}</a>`).join('\n');

  const cards = [];
  for (let i = 0; i < p.projects.length; i += 2) {
    const row = p.projects
      .slice(i, i + 2)
      .map((x) => `<a href="${x.url}">${pic(`project-${x.slug}`, `${x.title}: ${x.desc}`, 'width="49%"')}</a>`);
    cards.push(`<p>\n${row.join('\n')}\n</p>`);
  }

  const lab = p.lab.map((l) => `- [**${l.name}**](https://github.com/${p.username}/${l.repo}) · ${l.note}`).join('\n');

  const md = `<!-- Generated by scripts/readme.mjs. Edit data/profile.mjs, then run: npm run build -->

${pic('hero', `${p.name}: ${p.role}. ${p.typed[0]}.`)}

<p>
${links}
</p>

<br>

${pic('impact', `Impact: ${p.impact.map((i) => `${i.value} ${i.lines.join(' ')}`).join('; ')}.`)}

<br>

${pic('stack', `Full-stack request lifecycle: ${p.stack.map((s) => `${s.title} (${s.items.join(', ')})`).join(', ')}. Ship: ${p.ship.join(', ')}.`)}

<br>

${pic('header-work', '03. work')}

${cards.join('\n\n')}

<br>

${pic('header-lab', '04. lab')}

${lab}

<br>

${pic('path', `Career path: ${p.path.map((e) => `${e.when} ${e.what}`).join('; ')}.`)}

<br>

${pic('toolbox', `Toolbox: ${p.toolbox.flatMap((t) => t.items).join(', ')}.`)}

<br>

${pic('pulse', 'Pulse: live GitHub activity for the last year, rebuilt daily by a GitHub Action.')}

<br>

${pic('footer', 'Thanks for scrolling.')}
`;
  const file = join(ROOT, 'README.md');
  await writeFile(file, md);
  return file;
}
